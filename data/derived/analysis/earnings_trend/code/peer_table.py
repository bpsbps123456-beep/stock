def top_pct(ticker: str, tier: str, yoy: float) -> float:
    """'상위 X%'의 X(작을수록 좋음). 문턱 사이는 선형 보간, 상위 50% 문턱 아래는 75(하위 절반 한 칸)."""
    sec = SECTOR_OF.get(ticker)
    if sec is None or tier not in TIERS or yoy is None or np.isnan(yoy):
        return np.nan
    rows = T[sec]
    row = rows[TIERS.index(tier)] or rows[1]
    if yoy < row[0]:
        return 75.0
    if yoy >= row[-1]:
        return 1.0
    for i in range(len(row) - 1):
        if row[i] <= yoy < row[i + 1]:
            w = (yoy - row[i]) / (row[i + 1] - row[i])
            return TOPS[i] + w * (TOPS[i + 1] - TOPS[i])
    return np.nan
